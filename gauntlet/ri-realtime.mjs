import { chromium } from 'playwright';
import { serveRepo } from '../tools/screenshot.mjs';
const secs = Number(process.argv[2] || 20);
const { origin, close } = await serveRepo();
const b = await chromium.launch();
const p = await b.newPage({ viewport: { width: 1600, height: 900 } });
const errs = [];
p.on('console', (m) => { if (m.type() === 'error') errs.push(m.text()); });
p.on('pageerror', (e) => errs.push(String(e)));
p.on('requestfailed', (r) => errs.push('REQ ' + r.url()));
await p.goto(`${origin}/index.html?screen=race&track=${process.argv[3] || 'mt-coronet'}&racer=gengar`, { waitUntil: 'load' });
await p.waitForFunction(() => window.__pkr && window.__pkr.isReady, null, { timeout: 20000 });
await p.evaluate(() => window.__pkr.resume());
await p.waitForTimeout(secs * 1000);
const info = await p.evaluate(() => ({ screen: window.__pkr.screen(), hud: (window.__pkr.state().race || {}).hud }));
console.log(JSON.stringify(info));
await p.screenshot({ path: 'gauntlet/shots/ri-realtime.png' });
console.log(errs.length ? `FAIL ${errs.length} errors: ${errs.slice(0, 4).join(' | ')}` : 'PASS no console errors');
await b.close(); await close();
